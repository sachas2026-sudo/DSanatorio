import { describe, expect, it } from 'vitest'
import {
  buildDefaultDoctorHorarios,
  buildHorariosFranjasByDay,
  DEFAULT_DOCTOR_WEEKDAYS,
  doctorHorarioAtencionLabel,
  formatDiasAtencionRangePdf,
  formatHorarioCompactoPorDia,
  formatHorarioCompactoPorDiaPdf,
  groupHorariosByWeekday,
  horariosEfectivosDoctor,
  isAutoGeneratedDefaultHorarios,
} from './doctorAgenda'
import type { AppData, Doctor } from '../types'

describe('buildDefaultDoctorHorarios', () => {
  it('crea mañana y tarde de lunes a viernes', () => {
    let n = 0
    const horarios = buildDefaultDoctorHorarios('doc-1', () => `h-${++n}`)
    expect(horarios).toHaveLength(DEFAULT_DOCTOR_WEEKDAYS.length * 2)
    expect(horarios.every((h) => h.doctorId === 'doc-1')).toBe(true)
    expect(new Set(horarios.map((h) => h.diaSemana))).toEqual(
      new Set([1, 2, 3, 4, 5]),
    )
    const lunes = horarios.filter((h) => h.diaSemana === 1)
    expect(lunes.map((h) => `${h.horaInicio}-${h.horaFin}`)).toEqual([
      '08:00-11:30',
      '15:00-20:00',
    ])
  })
})

describe('horariosEfectivosDoctor', () => {
  it('trata el set automático como horario general (lista vacía)', () => {
    const horarios = buildDefaultDoctorHorarios('doc-1', () => `h-${Math.random()}`)
    expect(isAutoGeneratedDefaultHorarios('doc-1', horarios)).toBe(true)
    expect(horariosEfectivosDoctor('doc-1', horarios)).toEqual([])
  })

  it('conserva franjas personalizadas', () => {
    const custom = {
      id: 'h1',
      doctorId: 'doc-1',
      diaSemana: 3,
      horaInicio: '12:30',
      horaFin: '13:30',
    }
    expect(horariosEfectivosDoctor('doc-1', [custom])).toEqual([custom])
  })
})

describe('groupHorariosByWeekday', () => {
  it('agrupa y ordena por día y hora', () => {
    const grouped = groupHorariosByWeekday([
      {
        id: 'a',
        doctorId: 'd',
        diaSemana: 3,
        horaInicio: '12:30',
        horaFin: '13:30',
      },
      {
        id: 'b',
        doctorId: 'd',
        diaSemana: 1,
        horaInicio: '15:00',
        horaFin: '20:00',
      },
      {
        id: 'c',
        doctorId: 'd',
        diaSemana: 1,
        horaInicio: '08:00',
        horaFin: '11:30',
      },
    ])
    expect(grouped.map((g) => g.diaSemana)).toEqual([1, 3])
    expect(grouped[0]!.franjas.map((f) => f.horaInicio)).toEqual(['08:00', '15:00'])
  })
})

describe('formatDiasAtencionRangePdf', () => {
  it('pone rangos en dos líneas', () => {
    expect(formatDiasAtencionRangePdf([1, 2, 3, 4, 5])).toBe('Lunes\na Viernes')
  })

  it('une grupos con coma y salto de línea', () => {
    expect(formatDiasAtencionRangePdf([1, 2, 3, 6])).toBe(
      'Lunes\na Miércoles,\nSábado',
    )
  })
})

describe('formatHorarioCompactoPorDiaPdf', () => {
  it('agrupa dos días por línea con · y saltos de línea', () => {
    const byDay = buildHorariosFranjasByDay([
      { id: '1', doctorId: 'd', diaSemana: 1, horaInicio: '08:00', horaFin: '11:30' },
      { id: '2', doctorId: 'd', diaSemana: 1, horaInicio: '12:30', horaFin: '13:30' },
      { id: '3', doctorId: 'd', diaSemana: 1, horaInicio: '15:00', horaFin: '20:00' },
      { id: '4', doctorId: 'd', diaSemana: 2, horaInicio: '08:00', horaFin: '11:30' },
      { id: '5', doctorId: 'd', diaSemana: 2, horaInicio: '15:00', horaFin: '20:00' },
      { id: '6', doctorId: 'd', diaSemana: 3, horaInicio: '08:00', horaFin: '11:30' },
      { id: '7', doctorId: 'd', diaSemana: 3, horaInicio: '12:30', horaFin: '13:30' },
      { id: '8', doctorId: 'd', diaSemana: 3, horaInicio: '15:00', horaFin: '20:00' },
      { id: '9', doctorId: 'd', diaSemana: 4, horaInicio: '08:00', horaFin: '11:30' },
      { id: '10', doctorId: 'd', diaSemana: 4, horaInicio: '15:00', horaFin: '20:00' },
      { id: '11', doctorId: 'd', diaSemana: 5, horaInicio: '08:00', horaFin: '11:30' },
      { id: '12', doctorId: 'd', diaSemana: 5, horaInicio: '15:00', horaFin: '20:00' },
    ])
    expect(formatHorarioCompactoPorDiaPdf(byDay)).toBe(
      [
        'Lun 08:00–11:30, 12:30–13:30, 15:00–20:00· Mar 08:00–11:30  · 15:00–20:00',
        'Mié 08:00–11:30, 12:30–13:30, 15:00–20:00· Jue 08:00–11:30  · 15:00–20:00',
        'Vie 08:00–11:30  · 15:00–20:00',
      ].join('\n'),
    )
  })
})

